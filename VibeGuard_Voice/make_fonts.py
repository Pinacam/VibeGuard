"""
Builds vg_fonts.h: smooth (anti-aliased) fonts for the VibeGuard watch.

    python make_fonts.py

Uses the free DejaVu Sans font that comes with matplotlib. Each letter is
stored as 16 shades of transparency, so text edges look smooth on the
AMOLED screen instead of blocky.
"""

import os
from pathlib import Path

import matplotlib
from PIL import Image, ImageDraw, ImageFont

HERE = Path(__file__).resolve().parent
TTF = Path(matplotlib.__file__).parent / "mpl-data" / "fonts" / "ttf"

# name in the sketch, font file, pixel size
FONTS = [
    ("FONT_SMALL", "DejaVuSans.ttf", 17),      # clock, hints
    ("FONT_TEXT", "DejaVuSans.ttf", 21),       # captions, messages
    ("FONT_LABEL", "DejaVuSans-Bold.ttf", 30), # Listening..., mood name
    ("FONT_TITLE", "DejaVuSans-Bold.ttf", 34), # VibeGuard
]

FIRST, LAST = 32, 126


def build(name, ttf, size):
    font = ImageFont.truetype(str(TTF / ttf), size)
    ascent, descent = font.getmetrics()
    data = bytearray()
    glyphs = []
    for code in range(FIRST, LAST + 1):
        ch = chr(code)
        advance = round(font.getlength(ch))
        box = font.getbbox(ch)                 # left, top, right, bottom
        w, h = max(0, box[2] - box[0]), max(0, box[3] - box[1])
        offset = len(data)
        if w and h:
            img = Image.new("L", (w, h), 0)
            ImageDraw.Draw(img).text((-box[0], -box[1]), ch, font=font, fill=255)
            px = list(img.getdata())
            shades = [min(15, (v + 8) // 17) for v in px]
            if len(shades) % 2:
                shades.append(0)
            for i in range(0, len(shades), 2):
                data.append((shades[i] << 4) | shades[i + 1])
        # x offset, y offset from the baseline (negative = above it)
        glyphs.append((offset, w, h, box[0], box[1] - ascent, advance))

    lines = [f"// {ttf} {size}px"]
    lines.append(f"static const uint8_t {name}_BITMAP[] PROGMEM = {{")
    for i in range(0, len(data), 24):
        lines.append("  " + ",".join(f"0x{b:02X}" for b in data[i:i + 24]) + ",")
    lines.append("};")
    lines.append(f"static const VGGlyph {name}_GLYPHS[] PROGMEM = {{")
    for g in glyphs:
        lines.append("  {%d,%d,%d,%d,%d,%d}," % g)
    lines.append("};")
    lines.append(f"static const VGFont {name} = {{{name}_BITMAP, {name}_GLYPHS, "
                 f"{ascent}, {descent}}};")
    return "\n".join(lines), len(data)


def main():
    out = [
        "// Generated by make_fonts.py - DejaVu Sans (free licence).",
        "#pragma once",
        "#include <Arduino.h>",
        "",
        "struct VGGlyph {",
        "  uint32_t offset;     // where this letter starts in the bitmap",
        "  uint8_t width, height;",
        "  int8_t xOffset, yOffset;  // position relative to the pen / baseline",
        "  uint8_t advance;     // how far to move right afterwards",
        "};",
        "",
        "struct VGFont {",
        "  const uint8_t *bitmap;  // 2 pixels per byte, 16 shades each",
        "  const VGGlyph *glyphs;  // characters 32 to 126",
        "  uint8_t ascent, descent;",
        "};",
        "",
    ]
    total = 0
    for name, ttf, size in FONTS:
        text, n = build(name, ttf, size)
        out.append(text)
        out.append("")
        total += n
    (HERE / "vg_fonts.h").write_text("\n".join(out), encoding="utf-8")
    print(f"vg_fonts.h written, {total / 1024:.0f} KB of letter data")


if __name__ == "__main__":
    main()
